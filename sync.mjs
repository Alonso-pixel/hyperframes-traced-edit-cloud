#!/usr/bin/env node
// Re-export traced-edit from the hyperframes-videos workspace into this repo, and (optionally)
// push the asset library / a project to R2.
//
//   node sync.mjs                      copy the skill files + regenerate hermes/skills/traced-edit
//   node sync.mjs --assets             also: rclone sync videos/ASSETS -> r2:<bucket>/assets
//   node sync.mjs --project <name>     also: rclone copy videos/<name> -> r2:<bucket>/projects/<name>
//   node sync.mjs --check              only report what would change (no writes)
//
// The workspace is ../hyperframes-videos unless HF_WORKSPACE says otherwise. R2 credentials come
// from .env (R2_ACCOUNT_ID, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY, R2_BUCKET); see README.md.
// The workspace stays the source of truth: never hand-edit the copied folders here.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = dirname(fileURLToPath(import.meta.url));
const WS = resolve(process.env.HF_WORKSPACE || join(REPO, "..", "hyperframes-videos"));
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const opt = (k) => (args.includes(k) ? args[args.indexOf(k) + 1] : null);

// What the Codespace needs, mirrored at the same relative paths (the scripts find the workspace
// as SKILL/../../.. and music-score's lib.mjs as ../../../music-score/scripts/lib.mjs).
const COPY = [
  ".claude/skills/traced-edit",
  ".claude/skills/music-score",
  "tools/transcribe.mjs",
  "tools/find-asset.mjs",
  "tools/index-assets.mjs",
];
// Never exported: local caches and machine state.
const SKIP = /(^|[\\/])(node_modules|\.previews\.json|\.review\.json)$/;

if (!existsSync(join(WS, ".claude/skills/traced-edit/SKILL.md"))) {
  console.error(`no traced-edit skill under ${WS} (set HF_WORKSPACE)`);
  process.exit(1);
}

function walk(p) {
  if (statSync(p).isFile()) return [p];
  return readdirSync(p).flatMap((n) => (SKIP.test(n) ? [] : walk(join(p, n))));
}

let changed = 0;
for (const rel of COPY) {
  const src = join(WS, rel), dst = join(REPO, rel);
  if (!existsSync(src)) {
    console.log(`  (missing in workspace, skipped) ${rel}`);
    continue;
  }
  const files = walk(src);
  for (const f of files) {
    const to = join(dst, relative(src, f));
    const same = existsSync(to) && readFileSync(to).equals(readFileSync(f));
    if (same) continue;
    changed++;
    console.log(`  ${existsSync(to) ? "update" : "add   "} ${relative(REPO, to).replaceAll("\\", "/")}`);
    if (!CHECK) {
      mkdirSync(dirname(to), { recursive: true });
      cpSync(f, to);
    }
  }
  // files deleted in the workspace
  if (existsSync(dst) && statSync(dst).isDirectory()) {
    const keep = new Set(files.map((f) => relative(src, f)));
    for (const f of walk(dst)) {
      if (keep.has(relative(dst, f))) continue;
      changed++;
      console.log(`  remove ${relative(REPO, f).replaceAll("\\", "/")}`);
      if (!CHECK) rmSync(f);
    }
  }
}

// ---------- the Hermes skill: preamble + invariants + the original SKILL.md, verbatim ----------
const original = readFileSync(join(WS, ".claude/skills/traced-edit/SKILL.md"), "utf8").replace(/\r\n/g, "\n");
const fm = original.match(/^---\n([\s\S]*?)\n---\n/);
if (!fm) {
  console.error("traced-edit SKILL.md has no frontmatter");
  process.exit(1);
}
const body = original.slice(fm[0].length);
const description = fm[1].match(/description:\s*>\s*\n([\s\S]*)/)[1].split("\n").map((l) => l.trim()).filter(Boolean).join(" ");
const preamble = readFileSync(join(REPO, "hermes/PREAMBLE.md"), "utf8").replace(/\r\n/g, "\n");
const invariants = readFileSync(join(WS, "CLAUDE.md"), "utf8").replace(/\r\n/g, "\n").match(/## Invariants\n([\s\S]*?)\n## /)?.[1];
if (!invariants) {
  console.error("could not find '## Invariants' in the workspace CLAUDE.md");
  process.exit(1);
}
const hermesSkill = [
  "---",
  "name: traced-edit",
  `description: ${JSON.stringify("(Runs on the render Codespace through `renderbox`.) " + description)}`,
  "version: 1.0.0",
  "platforms: [linux]",
  "metadata:",
  "  hermes:",
  "    category: creative",
  "    tags: [video, hyperframes, editing, ffmpeg]",
  "    requires_toolsets: [terminal]",
  "---",
  "",
  "<!-- GENERATED by sync.mjs from hermes/PREAMBLE.md + the workspace CLAUDE.md + the workspace",
  "     traced-edit SKILL.md. Do not edit here: edit those and rerun `node sync.mjs`. -->",
  "",
  preamble.trim(),
  "",
  "## Workspace invariants (from the workspace CLAUDE.md)",
  "",
  invariants.trim(),
  "",
  "---",
  "",
  "# The original skill (verbatim; every command in it runs through `renderbox exec`)",
  "",
  body.trim(),
  "",
].join("\n");

const HS = join(REPO, "hermes/skills/traced-edit");
const outFiles = { "SKILL.md": hermesSkill };
for (const sub of ["references", "examples"]) {
  for (const f of walk(join(WS, ".claude/skills/traced-edit", sub))) {
    outFiles[join(sub, relative(join(WS, ".claude/skills/traced-edit", sub), f))] = readFileSync(f);
  }
}
for (const [rel, content] of Object.entries(outFiles)) {
  const to = join(HS, rel);
  const buf = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (existsSync(to) && readFileSync(to).equals(buf)) continue;
  changed++;
  console.log(`  ${existsSync(to) ? "update" : "add   "} ${relative(REPO, to).replaceAll("\\", "/")}`);
  if (!CHECK) {
    mkdirSync(dirname(to), { recursive: true });
    writeFileSync(to, buf);
  }
}
console.log(changed ? `${changed} file(s) ${CHECK ? "would change" : "changed"}.` : "already in sync.");

// ---------- R2 ----------
function loadEnv() {
  const f = join(REPO, ".env");
  if (!existsSync(f)) return {};
  return Object.fromEntries(
    readFileSync(f, "utf8").split(/\r?\n/).filter((l) => /^\s*[A-Z_]+=/.test(l)).map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, "")];
    }),
  );
}
function rclone(verb, from, to, extra = []) {
  const e = { ...loadEnv(), ...process.env };
  for (const k of ["R2_ACCOUNT_ID", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET"]) {
    if (!e[k]) {
      console.error(`${k} is not set (put it in .env)`);
      process.exit(1);
    }
  }
  const env = {
    ...e,
    RCLONE_CONFIG_R2_TYPE: "s3",
    RCLONE_CONFIG_R2_PROVIDER: "Cloudflare",
    RCLONE_CONFIG_R2_ACCESS_KEY_ID: e.R2_ACCESS_KEY_ID,
    RCLONE_CONFIG_R2_SECRET_ACCESS_KEY: e.R2_SECRET_ACCESS_KEY,
    RCLONE_CONFIG_R2_ENDPOINT: `https://${e.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
    RCLONE_CONFIG_R2_NO_CHECK_BUCKET: "true",
  };
  const dest = to.replace("r2:", `r2:${e.R2_BUCKET}/`);
  const a = [verb, from, dest, "--progress", "--transfers", "8", "--fast-list", ...extra, ...(CHECK ? ["--dry-run"] : [])];
  console.log(`$ rclone ${a.join(" ")}`);
  const r = spawnSync("rclone", a, { stdio: "inherit", env });
  if (r.error) {
    console.error(`rclone not found: install it (winget install Rclone.Rclone) — ${r.error.message}`);
    process.exit(1);
  }
  if (r.status !== 0) process.exit(r.status);
}
if (args.includes("--assets")) rclone("sync", join(WS, "videos/ASSETS"), "r2:assets");
const proj = opt("--project");
if (proj) {
  if (!existsSync(join(WS, "videos", proj))) {
    console.error(`no project videos/${proj} in the workspace`);
    process.exit(1);
  }
  rclone("copy", join(WS, "videos", proj), `r2:projects/${proj}`, ["--exclude", ".previews.json", "--exclude", ".review.json"]);
}
